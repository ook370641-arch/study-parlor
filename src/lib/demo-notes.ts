/**
 * 用户改写的文案：`{ [noteId]: { [path]: text } }`，落在 state.json。
 *
 * path 只覆盖「文本」，不覆盖结构（分节数量、列表长度、键值对数量由代码固定）：
 *   title | thesis | context
 *   | s{i}.heading | s{i}.p{j} | s{i}.b{j} | s{i}.kv{j}.key | s{i}.kv{j}.value
 *   | st{i}.title | st{i}.detail | m{i}.label | m{i}.detail | q{i}.q | q{i}.a
 * 空字符串视为「改回默认」，避免误删整段后留下空白。
 */
export type DemoNoteOverrides = Record<string, Record<string, string>>

function override(overrides: Record<string, string> | undefined, path: string, fallback: string): string {
  const v = overrides?.[path]
  // 只有空白也算「改回默认」：用户把一段删干净时不留下空白块
  return typeof v === 'string' && v.trim().length > 0 ? v : fallback
}

/** 把用户改写叠加到默认文案上；无改写时原样返回（保持引用，避免多余渲染） */
export function applyDemoNoteOverrides(note: DemoNote, overrides?: Record<string, string>): DemoNote {
  if (!overrides || Object.keys(overrides).length === 0) return note
  const ov = (path: string, fallback: string) => override(overrides, path, fallback)
  return {
    ...note,
    title: ov('title', note.title),
    thesis: ov('thesis', note.thesis),
    ...(note.context !== undefined ? { context: ov('context', note.context) } : {}),
    sections: note.sections.map((s, i) => ({
      ...s,
      heading: s.heading ? ov(`s${i}.heading`, s.heading) : s.heading,
      paragraphs: s.paragraphs?.map((p, j) => ov(`s${i}.p${j}`, p)),
      bullets: s.bullets?.map((b, j) => ov(`s${i}.b${j}`, b)),
      pairs: s.pairs?.map((pair, j) => ({
        key: ov(`s${i}.kv${j}.key`, pair.key),
        value: ov(`s${i}.kv${j}.value`, pair.value),
      })),
    })),
    steps: note.steps?.map((step, i) => ({
      title: ov(`st${i}.title`, step.title),
      detail: ov(`st${i}.detail`, step.detail),
    })),
    metrics: note.metrics?.map((metric, i) => ({
      label: ov(`m${i}.label`, metric.label),
      detail: ov(`m${i}.detail`, metric.detail),
    })),
    qa: note.qa?.map((item, i) => ({ q: ov(`q${i}.q`, item.q), a: ov(`q${i}.a`, item.a) })),
  }
}

/** 读取某个 path 当前（已叠加改写）的文本；用于外部点击前判断是否有未保存变更 */
export function readDemoNotePath(note: DemoNote, path: string): string | undefined {
  if (path === 'title') return note.title
  if (path === 'thesis') return note.thesis
  if (path === 'context') return note.context
  const section = /^s(\d+)\.(.+)$/.exec(path)
  if (section) {
    const s = note.sections[Number(section[1])]
    if (!s) return undefined
    const rest = section[2]
    if (rest === 'heading') return s.heading
    const para = /^p(\d+)$/.exec(rest)
    if (para) return s.paragraphs?.[Number(para[1])]
    const bullet = /^b(\d+)$/.exec(rest)
    if (bullet) return s.bullets?.[Number(bullet[1])]
    const kv = /^kv(\d+)\.(key|value)$/.exec(rest)
    if (kv) return s.pairs?.[Number(kv[1])]?.[kv[2] as 'key' | 'value']
    return undefined
  }
  const step = /^st(\d+)\.(title|detail)$/.exec(path)
  if (step) return note.steps?.[Number(step[1])]?.[step[2] as 'title' | 'detail']
  const metric = /^m(\d+)\.(label|detail)$/.exec(path)
  if (metric) return note.metrics?.[Number(metric[1])]?.[metric[2] as 'label' | 'detail']
  const qa = /^q(\d+)\.(q|a)$/.exec(path)
  if (qa) return note.qa?.[Number(qa[1])]?.[qa[2] as 'q' | 'a']
  return undefined
}
