/**
 * Demo 信息说明的唯一事实源。
 *
 * 每一条对应应用里一个 `i` 入口。这一组文案的读者设定是「第一次打开这款应用的人」，
 * 所以统一按同一副骨架写，顺序固定：
 *
 *   标题 → 一句话主张（thesis）→ 你现在看到的是什么（context）
 *   → 工作流（steps，可选）→ 分节（场景与问题 / 技术取舍 / 边界 / 下一步）
 *   → 指标（metrics，可选）→ 可能被追问（qa）
 *
 * 三条硬约束：
 * 1. 只写当前代码真实存在的行为（可被仓库检索验证），不写规划中的能力；
 * 2. 先讲用户场景与产品判断，再讲技术；技术段落必须落到「为什么这样选、代价是什么」；
 * 3. 不假设读者懂本应用的术语——出现内部叫法时，当场用一句人话解释。
 *
 * 改代码后若与本文件不一致，以代码为准并同步本文件。
 */

export type DemoNoteSection = {
  /** 小节标题；空字符串表示不渲染标题 */
  heading: string
  /** 段落（纯文本，逐段渲染） */
  paragraphs?: string[]
  /** 列表项 */
  bullets?: string[]
  /** 键值对（选型对照、取舍代价） */
  pairs?: Array<{ key: string; value: string }>
}

/** 工作流的一步：短标题 + 一句在做什么 */
export type DemoNoteStep = { title: string; detail: string }

/** 一个指标：名称 + 口径与判断标准 */
export type DemoNoteMetric = { label: string; detail: string }

export type DemoNote = {
  id: 'book-source' | 'guide' | 'annotation' | 'review' | 'learning-chart' | 'external-materials'
  title: string
  /** 一句话主线，弹层顶部高亮 */
  thesis: string
  /** 「你现在看到的是什么」——给第一次看到这个功能的人定位 */
  context?: string
  /** 工作流：有明确多步链路的入口才写 */
  steps?: DemoNoteStep[]
  sections: DemoNoteSection[]
  /** 怎么衡量；口径写在 detail 里，避免只给一个指标名 */
  metrics?: DemoNoteMetric[]
  /** 可能被追问的点：现场可直接念 */
  qa?: Array<{ q: string; a: string }>
}

